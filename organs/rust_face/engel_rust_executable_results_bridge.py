#!/usr/bin/env python3
"""Safe Python bridge to the Rust Engel executable-result generator."""
from __future__ import annotations

import json
import os
from pathlib import Path
import subprocess
from typing import Any

from engel_project_paths import resolve_engel_app_root


ENGEL_APP_ROOT = resolve_engel_app_root(__file__)


def _rust_executable() -> Path | None:
    configured = os.environ.get("ENGEL_AI_RS_EXE", "").strip()
    candidates = []
    if configured:
        candidates.append(Path(configured))
    candidates.extend([
        ENGEL_APP_ROOT / "rust" / "engel-core-rs" / "target" / "debug" / "engel-ai-rs.exe",
        ENGEL_APP_ROOT / "rust" / "engel-core-rs" / "target" / "release" / "engel-ai-rs.exe",
    ])
    for candidate in candidates:
        if candidate.is_file():
            return candidate
    return None


def execute_rust_ui_result_request(
    prompt: str,
    meeting_summary: str = "",
    returned_previews: list[str] | None = None,
) -> dict[str, Any]:
    """Create an Engel artifact through `engel-ai-rs executable-results create`."""
    exe = _rust_executable()
    if exe is None:
        return {
            "accepted": False,
            "reason": "engel-ai-rs executable not built",
            "runtime": "engel-ai-rs",
        }

    cmd = [
        str(exe),
        "executable-results",
        "create",
        "--meeting-summary",
        str(meeting_summary or ""),
    ]
    artifact_root = os.environ.get("ENGEL_EXECUTABLE_RESULTS_DIR", "").strip()
    if artifact_root:
        cmd.extend(["--artifact-root", artifact_root])
    for preview in returned_previews or []:
        if str(preview).strip():
            cmd.extend(["--returned-preview", str(preview)])
    cmd.append(str(prompt or ""))

    run = subprocess.run(
        cmd,
        cwd=str(ENGEL_APP_ROOT),
        text=True,
        capture_output=True,
        timeout=120,
        check=False,
    )
    if run.returncode != 0:
        return {
            "accepted": False,
            "reason": f"engel-ai-rs failed with exit code {run.returncode}",
            "runtime": "engel-ai-rs",
            "stderr": run.stderr.strip(),
        }
    try:
        payload = json.loads(run.stdout)
    except json.JSONDecodeError as exc:
        return {
            "accepted": False,
            "reason": f"engel-ai-rs returned invalid JSON: {exc}",
            "runtime": "engel-ai-rs",
            "stdout": run.stdout.strip(),
        }
    if payload.get("accepted"):
        payload.setdefault("runtime", "engel-ai-rs")
        payload.setdefault("notes", [
            "Generated by Rust-native Engel executable result creator.",
            "Artifacts are local files; generated code is not auto-executed.",
            "Phone worker previews are context only and remain review-required.",
        ])
    return payload

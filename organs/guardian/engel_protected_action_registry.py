ACTION_BY_ID = {str(action["action_id"]): action for action in PROTECTED_ACTIONS}


def list_actions() -> list[dict[str, object]]:
    return [dict(action) for action in PROTECTED_ACTIONS]


def get_action(action_id: str) -> dict[str, object] | None:
    action = ACTION_BY_ID.get(action_id)
    return dict(action) if action is not None else None


def registry_summary() -> dict[str, object]:
    counts = {risk: 0 for risk in RISK_LEVELS}
    categories: dict[str, int] = {}
    password_required = 0
    for action in PROTECTED_ACTIONS:
        counts[str(action["risk_level"])] += 1
        categories[str(action["category"])] = categories.get(str(action["category"]), 0) + 1
        if action.get("password_required"):
            password_required += 1
    return {
        "status": list(REGISTRY_STATUS),
        "action_count": len(PROTECTED_ACTIONS),
        "risk_counts": counts,
        "category_counts": categories,
        "password_required_count": password_required,
        "blocked_count": counts["blocked"],
    }


def render_action_list() -> str:
    summary = registry_summary()
    lines = [
        "Engel Protected Action Registry V1",
        "",
        "Status:",
        *[f"- {status}" for status in REGISTRY_STATUS],
        "",
        "Risk counts:",
    ]
    for risk, count in summary["risk_counts"].items():
        lines.append(f"- {risk}: {count}")
    lines.extend(["", "Actions:"])
    for action in PROTECTED_ACTIONS:
        lines.append(
            f"- {action['action_id']} | {action['category']} | {action['risk_level']} | "
            f"password_required={action['password_required']} | state={action['current_state']}"
        )
    lines.extend(
        [
            "",
            "Boundary:",
            "- This registry describes gates only; it does not execute protected actions.",
            "- Blocked actions remain blocked even with password verification.",
            "- Password protects actions; it does not bypass safety.",
        ]
    )
    return "\n".join(lines).rstrip() + "\n"


def render_action_detail(action_id: str) -> str:
    action = get_action(action_id)
    if action is None:
        return "Unknown protected action.\n"
    lines = ["Engel Protected Action", ""]
    for field in REQUIRED_ACTION_FIELDS:
        value = action.get(field)
        if isinstance(value, list):
            rendered = ", ".join(str(item) for item in value) if value else "none"
        else:
            rendered = str(value)
        lines.append(f"{field}: {rendered}")
    return "\n".join(lines).rstrip() + "\n"


def registry_payload() -> dict[str, object]:
    return {
        "schema_version": "1.0",
        "status": list(REGISTRY_STATUS),
        "required_action_fields": list(REQUIRED_ACTION_FIELDS),
        "risk_levels": list(RISK_LEVELS),
        "summary": registry_summary(),
        "actions": list_actions(),
        "boundary": "Registry only; no action execution.",
    }


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Read Engel protected action registry.")
    parser.add_argument("--list", action="store_true", help="List registered protected actions.")
    parser.add_argument("--show", metavar="ACTION_ID", help="Show one protected action.")
    parser.add_argument("--json", action="store_true", help="Print registry JSON.")
    return parser


def main(argv: list[str] | None = None, stdout=None, stderr=None) -> int:
    out = sys.stdout if stdout is None else stdout
    err = sys.stderr if stderr is None else stderr
    args = build_parser().parse_args(argv)
    modes = [args.list, bool(args.show), args.json]
    if not any(modes):
        out.write(render_action_list())
        return 0
    if sum(1 for mode in modes if mode) != 1:
        err.write("Choose exactly one registry display mode.\n")
        return 2
    if args.list:
        out.write(render_action_list())
        return 0
    if args.json:
        out.write(json.dumps(registry_payload(), indent=2, sort_keys=True) + "\n")
        return 0
    action = get_action(str(args.show))
    if action is None:
        err.write("Unknown protected action.\n")
        return 1
    out.write(render_action_detail(str(args.show)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

def _action(
    action_id: str,
    display_name: str,
    category: str,
    risk_level: str,
    *,
    password_required: bool,
    approval_token_required: bool = False,
    contract_required: bool = False,
    verifier_required: bool = False,
    receipt_required: bool = False,
    dry_run_required_first: bool = False,
    allowed_in_gui: bool = False,
    allowed_in_cli: bool = True,
    current_state: str = "available_with_gate",
    blocked_reason: str = "",
    required_contracts: list[str] | None = None,
    required_verifiers: list[str] | None = None,
    required_receipt_folder: str = "",
    safety_boundary: str = "",
    forbidden_without_extra_approval: list[str] | None = None,
    notes: str = "",
) -> dict[str, object]:
    if risk_level not in RISK_LEVELS:
        raise ValueError("unknown risk level for protected action registry")
    return {
        "action_id": action_id,
        "display_name": display_name,
        "category": category,
        "risk_level": risk_level,
        "password_required": password_required,
        "approval_token_required": approval_token_required,
        "contract_required": contract_required,
        "verifier_required": verifier_required,
        "receipt_required": receipt_required,
        "dry_run_required_first": dry_run_required_first,
        "allowed_in_gui": allowed_in_gui,
        "allowed_in_cli": allowed_in_cli,
        "current_state": current_state,
        "blocked_reason": blocked_reason,
        "required_contracts": required_contracts or [],
        "required_verifiers": required_verifiers or [],
        "required_receipt_folder": required_receipt_folder,
        "safety_boundary": safety_boundary,
        "forbidden_without_extra_approval": forbidden_without_extra_approval or [],
        "notes": notes,
    }


